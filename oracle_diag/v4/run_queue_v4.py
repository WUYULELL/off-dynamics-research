"""A reviewable, group-ordered queue with independent smoke/formal approval gates."""
from support_v4 import *
import argparse
import subprocess
import traceback


def plan():
    jobs=[]
    codes={'TARGET':'t','ORACLE-ONLY':'o','SOURCE-ONLY':'s','TARGET-64':'h','ORACLE-W1':'w'}
    for method in ALL_METHODS:
        jobs.append(dict(kind='smoke',method=method,seed=0,steps=5000,out=str(OUT/'s1'/(codes[method]+'0'))))
    for method in METHODS:
        for seed in range(5):
            jobs.append(dict(kind='formal',method=method,seed=seed,steps=500000,out=str(OUT/'b1'/(codes[method]+str(seed)))))
    for job in jobs:
        job['command']=[str(PYTHON),'-B',str(HERE/'train_entry_v4.py'),'--method',job['method'],
            '--seed',str(job['seed']),'--steps',str(job['steps']),'--out',job['out']]
    return dict(jobs=jobs,smoke_jobs=5,formal_jobs=20,formal_updates=10000000,
        approval='Separate explicit smoke and formal receipts. No authorization is generated by code.',
        ordering=list(METHODS),midpoint='After 10 formal jobs, write Q1/Q2 interim report; continue queue',
        runtime_prior_hours=51.,recovery='Nonempty incomplete output is refused; new attempt path after diagnosis only',
        execution='Serial GPU subprocess; 2 CPU threads; windows hidden; no other app is terminated')


def cpu_command(script,*args):
    env=dict(os.environ,CUDA_VISIBLE_DEVICES='-1',PYTHONDONTWRITEBYTECODE='1')
    subprocess.run([str(PYTHON),'-B',str(HERE/script)]+list(args),cwd=str(ROOT),env=env,check=True,
                   creationflags=getattr(subprocess,'CREATE_NO_WINDOW',0))


def main():
    parser=argparse.ArgumentParser();parser.add_argument('--kind',choices=('smoke','formal'))
    parser.add_argument('--plan',action='store_true');a=parser.parse_args()
    if a.plan:
        write(OUT/'training_plan.json',plan());print('Plan prepared; no training launched');return
    if a.kind is None:parser.error('--kind required')
    check_approval(a.kind)
    queue=read(OUT/'training_plan.json');jobs=[j for j in queue['jobs'] if j['kind']==a.kind]
    lock=OUT/'queue.lock'
    with open(str(lock),'x',encoding='utf-8') as f:
        json.dump(dict(pid=os.getpid(),kind=a.kind,created=time.time()),f)
    try:
        for index,job in enumerate(jobs):
            # Optional cancel receipt is checked only between jobs; no other process is touched.
            if (OUT/'cancel_remaining.json').exists():
                write(OUT/'queue_status.json',dict(state='cancelled_by_user_between_jobs',kind=a.kind,next_job=job),replace=True)
                return
            out=Path(job['out'])
            if (out/'completed.json').exists():
                done=read(out/'completed.json');assert all(done[k]==job[k] for k in ('method','seed','steps'))
            else:
                if out.exists() and any(out.iterdir()):
                    raise RuntimeError('Incomplete output preserved; diagnose and create new attempt: '+str(out))
                out.parent.mkdir(parents=True,exist_ok=True)
                with open(str(out.parent/(out.name+'.stdout.log')),'x',encoding='utf-8') as stdout, open(str(out.parent/(out.name+'.stderr.log')),'x',encoding='utf-8') as stderr:
                    child=subprocess.Popen(job['command'],cwd=str(ROOT),stdout=stdout,stderr=stderr,
                        creationflags=getattr(subprocess,'CREATE_NO_WINDOW',0))
                    write(OUT/'queue_status.json',dict(state='running',kind=a.kind,queue_pid=os.getpid(),pid=child.pid,
                        job=job,index=index,started=time.time()),replace=True)
                    code=child.wait()
                if code or not (out/'completed.json').exists():
                    raise RuntimeError('Training failed; evidence retained: '+str(out))
            if a.kind=='formal' and index==9:
                if not (OUT/'interim_audited.json').exists():cpu_command('audit_v4.py','--kind','interim')
                if not (HERE/'INTERIM_v4.md').exists():cpu_command('report_v4.py','--kind','interim')
                write(OUT/'interim_ready.json',dict(report=str(HERE/'INTERIM_v4.md'),created=time.time(),
                    next_action='Notify user; formal queue continues unless user cancels'),replace=True)
        if not (OUT/(a.kind+'_audited.json')).exists():cpu_command('audit_v4.py','--kind',a.kind)
        if a.kind=='formal':cpu_command('report_v4.py','--kind','final')
        write(OUT/'queue_status.json',dict(state='awaiting_formal_approval' if a.kind=='smoke' else 'completed',
            kind=a.kind,ended=time.time()),replace=True)
    except BaseException:
        write(OUT/('failure_'+str(time.time_ns())+'.json'),dict(kind=a.kind,error=traceback.format_exc(),created=time.time()))
        write(OUT/'queue_status.json',dict(state='failed',kind=a.kind,ended=time.time()),replace=True)
        raise
    finally:
        lock.unlink()


if __name__=='__main__':main()
